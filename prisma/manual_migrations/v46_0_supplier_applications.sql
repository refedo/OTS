-- V46.0 / Supplier intake: strictly separate application data and approved supplier master.
-- Idempotent, additive. Never seeds approvals or third-party records.
CREATE TABLE IF NOT EXISTS `ScSupplierApplication` (
  `id` CHAR(36) NOT NULL,
  `reference` VARCHAR(40) NOT NULL,
  `legalName` VARCHAR(200) NOT NULL,
  `registrationNumber` VARCHAR(100) NOT NULL,
  `registrationCountry` VARCHAR(100) NOT NULL,
  `contactName` VARCHAR(120) NOT NULL,
  `email` VARCHAR(250) NOT NULL,
  `phone` VARCHAR(35) NOT NULL,
  `companyWebsite` VARCHAR(250) NULL,
  `supplierType` VARCHAR(30) NOT NULL,
  `scope` VARCHAR(20) NOT NULL,
  `category` VARCHAR(120) NULL,
  `products` JSON NOT NULL,
  `services` TEXT NULL,
  `capabilities` TEXT NULL,
  `documents` JSON NOT NULL,
  `status` VARCHAR(24) NOT NULL DEFAULT 'SUBMITTED',
  `publicMessage` TEXT NULL,
  `internalNotes` TEXT NULL,
  `reviewHistory` JSON NOT NULL,
  `reviewedById` CHAR(36) NULL,
  `approvedSupplierId` CHAR(36) NULL,
  `otpHash` VARCHAR(64) NULL,
  `otpExpiresAt` DATETIME(3) NULL,
  `otpAttempts` INT NOT NULL DEFAULT 0,
  `otpSentAt` DATETIME(3) NULL,
  `otpDailyCount` INT NOT NULL DEFAULT 0,
  `otpDay` VARCHAR(10) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `ScSupplierApplication_reference_key` (`reference`),
  UNIQUE KEY `ScSupplierApplication_approvedSupplierId_key` (`approvedSupplierId`),
  KEY `ScSupplierApplication_status_createdAt_idx` (`status`, `createdAt`),
  KEY `ScSupplierApplication_email_idx` (`email`),
  KEY `ScSupplierApplication_reg_idx` (`registrationNumber`, `registrationCountry`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
